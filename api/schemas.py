"""Strict public API schemas."""
from enum import Enum
from typing import Any
from uuid import UUID

from pydantic import AnyHttpUrl, BaseModel, ConfigDict, Field, field_validator


class Action(str, Enum):
    ALLOW = "ALLOW"
    BLOCK = "BLOCK"


class Category(str, Enum):
    SAFE = "Safe_Use"
    PII = "PII_Leak"
    CODE = "Proprietary_Code"
    BUSINESS = "Business_Secrets"
    CODE_EXPLOITATION = "Code_Exploitation"
    DATA_EXFILTRATION = "Data_Exfiltration"
    SOCIAL_ENGINEERING = "Social_Engineering"
    ROLE_EVASION = "Role_Evasion_Jailbreak"
    LEGAL_MISALIGNMENT = "Legal_Misalignment"


class AuditRequest(BaseModel):
    user_id: UUID = Field(description="Anonymous UUID v4 generated by the browser")
    prompt: str = Field(min_length=1, max_length=4096)
    destination: AnyHttpUrl

    @field_validator("user_id")
    @classmethod
    def require_uuid4(cls, value: UUID):
        if value.version != 4:
            raise ValueError("user_id must be UUID v4")
        return value

    @field_validator("prompt")
    @classmethod
    def reject_blank(cls, value: str):
        if not value.strip():
            raise ValueError("prompt cannot be blank")
        return value

    @field_validator("destination")
    @classmethod
    def allowed_destination(cls, value: AnyHttpUrl):
        # The bundled sandbox is a local audit destination, not an external AI.
        if (value.scheme == "http" and value.host in {"127.0.0.1", "localhost"}
                and value.port == 8000 and value.path in {"/", "/sandbox", "/sandbox/"}
                and not value.username and not value.password and not value.query and not value.fragment):
            return value
        allowed = {
            "chatgpt.com", "claude.ai", "gemini.google.com", "copilot.microsoft.com",
            "www.perplexity.ai", "grok.com", "x.com", "chat.mistral.ai",
            "chat.deepseek.com", "poe.com", "you.com",
        }
        if value.host not in allowed and not (value.host or "").endswith(".chatgpt.com"):
            raise ValueError("unsupported GenAI destination")
        return value


class AuditResponse(BaseModel):
    action: Action
    risk_score: float = Field(ge=0, le=1)
    category: Category
    reason: str | None = None
    model_version: str = "dlp-slm-v2.0"
    inference_time_ms: float = Field(ge=0)
    redacted_preview: str
    matched_rules: list[str] = Field(default_factory=list)


class HealthResponse(BaseModel):
    model_config = ConfigDict(protected_namespaces=())
    status: str
    model_loaded: bool
    model_backend: str
    model_version: str
    database_connected: bool
    total_logs_recorded: int
    system_latency_p95_target: str = "<50ms"


class LogItem(BaseModel):
    model_config = ConfigDict(protected_namespaces=())
    id: int; timestamp: str; user_id: str; prompt_hash: str; prompt_redacted: str
    destination: str | None; action: Action; category: Category
    risk_score: float; confidence: float; model_version: str; inference_time_ms: float


class KpisResponse(BaseModel):
    total_audited: int; total_last_24h: int; total_blocked: int; total_allowed: int
    block_rate_pct: float; avg_risk_score: float; top_categories: dict[str, int]
    high_risk_users: list[dict[str, Any]]; recent_trend: list[dict[str, Any]]
